#!/usr/bin/env node
// The figures the site shows, as one Markdown sheet read from data/*.json.
// Run it before publishing and compare with the last sheet (git diff NUMBERS.md):
//   node scripts/numbers.mjs > NUMBERS.md
import { readFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const read = (f) => JSON.parse(readFileSync(join(ROOT, "data", f), "utf8"));
const pct = (x) => (x == null ? "n/a" : `${(x * 100).toFixed(1)}%`);
const num = (x) => (x == null ? "n/a" : x.toLocaleString("en"));
const GROUPS = [["member", "Member"], ["consortium", "via consortium"], ["direct", "direct"], ["none", "Not a member"]];
const PERIODS = [["up to 2021", (y) => y <= 2021], ["2022-2023", (y) => y === 2022 || y === 2023], ["2024 or later", (y) => y >= 2024]];

const ov = read("overview.json"), links = read("links.json"), cont = read("continents.json").continents;
const tl = read("timeline.json").years, fields = read("fields.json"), signup = read("signup.json").groups;
const ids = read("employer-ids.json").groups;

const out = ["# Figures shown on the site", "", "Generated by `node scripts/numbers.mjs` from `data/`.", "",
  `Data generated ${ov.generatedAt}; profiles fetched ${ov.harvest.from} to ${ov.harvest.to}, at most ${num(ov.maxPerInstitution)} per institution; ORCID member list of ${ov.memberList}.`, "",
  "| Figure | " + GROUPS.map(([, l]) => l).join(" | ") + " |", "|---|" + GROUPS.map(() => "---|").join("")];
const row = (label, f) => out.push(`| ${label} | ${GROUPS.map(([g]) => f(g)).join(" | ")} |`);

row("Institutions with profiles / sampled (truncated at the cap)", (g) => `${ov.groups[g].institutions} / ${ov.groups[g].sampled} (${ov.groups[g].truncated})`);
row("Profiles", (g) => num(ov.groups[g].profiles));
row("Completeness, all / current staff", (g) => `${pct(ov.groups[g].avgOverall)} / ${pct(ov.groups[g].staff.avgOverall)}`);
row("Without works, all / current staff", (g) => `${pct(ov.groups[g].empty)} / ${pct(ov.groups[g].staff.empty)}`);
for (const l of links.links) {
  row(`Link ${l}: profiles (share), completeness, without works`, (g) => {
    const c = links.groups[g][l];
    return `${num(c.profiles)} (${pct(c.profiles / ov.groups[g].profiles)}), ${pct(c.avgOverall)}, ${pct(c.empty)}`;
  });
}
for (const c of Object.keys(cont).sort()) {
  row(`${c}: institutions, profiles, completeness`, (g) => `${cont[c][g].institutions}, ${num(cont[c][g].profiles)}, ${pct(cont[c][g].avgOverall)}`);
}
for (const [id] of Object.entries(fields.checks)) row(`Check ${id}`, (g) => pct(fields.checks[id][g].share));
for (const [id] of Object.entries(fields.categories)) row(`Category ${id}`, (g) => pct(fields.categories[id][g]));
for (const y of Object.keys(tl).sort()) {
  row(`Created ${y}: profiles, completeness, without works`, (g) => `${num(tl[y][g].profiles)}, ${pct(tl[y][g].avgOverall)}, ${pct(tl[y][g].empty)}`);
}
for (const y of Object.keys({ ...signup.member, ...signup.none }).sort()) {
  row(`Employment here added ${y}: entries, at sign-up, by a system`, (g) => {
    const k = Object.values(signup[g][y] || {});
    const e = k.reduce((a, c) => a + c.entries, 0);
    return e ? `${num(e)}, ${pct(k.reduce((a, c) => a + c.atSignup, 0) / e)}, ${pct(k.reduce((a, c) => a + c.byClient, 0) / e)}` : "n/a";
  });
}
for (const [label, keep] of PERIODS) {
  row(`Employer elsewhere by ROR, added ${label}`, (g) => {
    const ys = Object.entries(ids[g]).filter(([y]) => keep(+y)).map(([, v]) => v);
    const e = ys.reduce((a, v) => a + v.entries, 0);
    return e ? `${pct(ys.reduce((a, v) => a + v.ror, 0) / e)} of ${num(e)}` : "n/a";
  });
}
const wr = read("writers.json");
const WP = [["all years", () => true], ...PERIODS];
for (const sec of wr.sections) {
  for (const [label, keep] of WP) {
    row(`Entries ${sec}, added ${label}: n; ${wr.kinds.join(" / ")}`, (g) => {
      const ys = Object.entries(wr.groups[g][sec] || {}).filter(([y]) => keep(+y)).map(([, v]) => v);
      const n = ys.reduce((a, v) => a + Object.values(v).reduce((x, y) => x + y, 0), 0);
      return n ? `${num(n)}; ` + wr.kinds.map((k) => pct(ys.reduce((a, v) => a + (v[k] || 0), 0) / n)).join(" / ") : "n/a";
    });
  }
}
const ws = wr.members.writes, wo = wr.members.other;
out.push("", `Members whose own system wrote at least ${pct(wr.ownMin)} of the employment entries with them, of their other affiliations or of their works: ` +
  `${ws.institutions} institutions, ${num(ws.profiles)} profiles, completeness ${pct(ws.avgOverall)}, without works ${pct(ws.empty)}. ` +
  `Other members: ${wo.institutions} institutions, ${num(wo.profiles)} profiles, completeness ${pct(wo.avgOverall)}, without works ${pct(wo.empty)}.`);
const ys = Object.keys(ws.years).filter((y) => ws.years[y].avgOverall != null && wo.years[y]?.avgOverall != null).sort();
out.push("", "| Created | Writes: profiles, completeness | Other members: profiles, completeness |", "|---|---|---|",
  ...ys.map((y) => `| ${y} | ${num(ws.years[y].profiles)}, ${pct(ws.years[y].avgOverall)} | ${num(wo.years[y].profiles)}, ${pct(wo.years[y].avgOverall)} |`));
const ownRows = read("institutions.json").institutions.filter((r) => r.own && (r.own.here || r.own.affiliations || r.own.works)).sort((a, b) => b.own.works + b.own.here + b.own.affiliations - a.own.works - a.own.here - a.own.affiliations);
out.push("", "| Institution | Membership | Employment here by own system | Other affiliations by own system | Works by own system |", "|---|---|---|---|---|",
  ...ownRows.map((r) => `| ${r.name} | ${r.membership} | ${num(r.own.here)} of ${num(r.own.hereEntries)} | ${num(r.own.affiliations)} of ${num(r.own.affiliationsEntries)} | ${num(r.own.works)} of ${num(r.own.worksEntries)} |`));
out.push("", "| Organisation | Entries | Institutions |", "|---|---|---|", ...wr.organisations.map((o) => `| ${o.name.trim()} | ${num(o.entries)} | ${o.institutions} |`));
console.log(out.join("\n"));
